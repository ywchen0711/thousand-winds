// Hand-drawn monsters. Every silhouette is placed pixel by pixel in the grids below; the code only
// shades each material from light (top left) to dark (bottom right) and adds a dark outline, the way
// 16-bit sprites were finished. A row given as half of the picture is mirrored to make the other half.
import { canvas } from './gfx.js';

// '.' is empty; a b c d are shaded materials; the other letters are flat colours
const FLAT = { w: '#f8f8f8', k: '#181018', r: '#e02828', R: '#f87850', y: '#f8d838', Y: '#c89018', g: '#48e070', e: '#60e8f8', E: '#2890c8', p: '#f080b0', s: '#d8d0c0', m: '#701818', o: '#201018' };
const mirror = (rows) => rows.map((r) => r + [...r].reverse().join(''));
function make(def) {
  const rows = def.half ? mirror(def.half) : [...def.rows];
  if (new Set(rows.map((r) => r.length)).size > 1) throw new Error('uneven monster rows: ' + rows.map((r) => r.length).join(','));
  const h = rows.length, w = Math.max(...rows.map((r) => r.length));
  const at = (x, y) => (x < 0 || y < 0 || x >= w || y >= h ? '.' : rows[y][x] || '.');
  for (const [x, y, ch] of def.over || []) { const r = rows[y]; rows[y] = r.slice(0, x) + ch + r.slice(x + ch.length); }
  const c = canvas(w + 2, h + 2), id = c.x.createImageData(w + 2, h + 2), d = id.data;
  const put = (x, y, hexc) => { const i = ((y + 1) * (w + 2) + x + 1) * 4, n = parseInt(hexc.slice(1), 16); d[i] = n >> 16; d[i + 1] = (n >> 8) & 255; d[i + 2] = n & 255; d[i + 3] = 255; };
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const ch = at(x, y);
    if (ch === '.') continue;
    const ramp = def.pal[ch];
    if (!ramp) { put(x, y, FLAT[ch] || '#ff00ff'); continue; }
    // light from the top left: an edge above or to the left brightens, an edge below or to the right darkens
    const other = (dx, dy) => at(x + dx, y + dy) !== ch;
    let lv = 2;
    if (other(-1, 0) || other(0, -1)) lv++;
    if (other(-1, -1) && !other(-1, 0) && !other(0, -1)) lv += 0;
    if (other(1, 0) || other(0, 1)) lv--;
    if (other(2, 0) || other(0, 2)) lv -= other(1, 0) || other(0, 1) ? 0 : 1;
    if (!other(-1, 0) && !other(0, -1) && (other(-2, 0) || other(0, -2))) lv += 0.5;
    lv += (0.5 - y / h) * (def.grad === undefined ? 1.2 : def.grad);
    put(x, y, ramp[Math.max(0, Math.min(ramp.length - 1, Math.round(lv)))]);
  }
  // the outline: every empty pixel touching the picture becomes the darkest ink
  const ink = def.ink || '#140c14';
  const filled = (x, y) => x >= 0 && y >= 0 && x < w + 2 && y < h + 2 && d[(y * (w + 2) + x) * 4 + 3] === 255;
  const out = [];
  for (let y = 0; y < h + 2; y++) for (let x = 0; x < w + 2; x++) if (!filled(x, y) && (filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1))) out.push([x, y]);
  for (const [x, y] of out) { const i = (y * (w + 2) + x) * 4, n = parseInt(ink.slice(1), 16); d[i] = n >> 16; d[i + 1] = (n >> 8) & 255; d[i + 2] = n & 255; d[i + 3] = 255; }
  c.x.putImageData(id, 0, 0);
  return c;
}
