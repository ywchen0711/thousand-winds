const cache = new Map();
export const hasPix = (k) => !!PIX[k];
export function pixArt(k) {
  if (!cache.has(k)) cache.set(k, make(PIX[k]));
  return cache.get(k);
}
// the small version for the field: every second pixel, then outlined again
export function pixMini(k) {
  const key = 'mini:' + k;
  if (cache.has(key)) return cache.get(key);
  const a = pixArt(k), sc = Math.max(1, Math.ceil(Math.max(a.width, a.height) / 18));
  const c = canvas(Math.ceil(a.width / sc), Math.ceil(a.height / sc));
  c.x.imageSmoothingEnabled = false;
  c.x.drawImage(a, 0, 0, c.width, c.height);
  cache.set(key, c);
  return c;
}
